import React from 'react'
import {
  Body,
  Container,
  Head,
  Heading,
  Hr,
  Html,
  Link,
  Preview,
  Section,
  Text,
} from '@react-email/components'
import type { TemplateEntry } from './registry'

interface Item {
  title: string
  url: string
  source: string
  countryName: string | null
  fuels: string[]
}

interface Props {
  dateLabel?: string
  imageUrl?: string
  items?: Item[]
}

const main = { backgroundColor: '#f6f7f9', fontFamily: 'Calibri, Carlito, Segoe UI, Arial, sans-serif' }
const container = { padding: '0 0 24px', maxWidth: '620px' }
const banner = {
  background: 'linear-gradient(90deg, #0b1220 0%, #16213e 100%)',
  backgroundColor: '#0b1220',
  padding: '22px 28px',
  borderRadius: '12px 12px 0 0',
}
const bannerTitle = { fontSize: '24px', fontWeight: 700, color: '#ffffff', margin: '0' }
const bannerSub = { fontSize: '13px', color: '#94a3b8', margin: '6px 0 0' }
const inner = { padding: '20px 28px 0', backgroundColor: '#ffffff' }
const imageWrap = { padding: '0 28px 20px', backgroundColor: '#ffffff' }
const image = { maxWidth: '100%', height: 'auto', borderRadius: '10px', border: '1px solid #e4e8ef' }
const kicker = {
  fontSize: '11px',
  letterSpacing: '0.09em',
  textTransform: 'uppercase' as const,
  color: '#6b7484',
  margin: '0 0 12px',
}
const card = {
  border: '1px solid #e4e8ef',
  borderLeft: '4px solid #1d4ed8',
  borderRadius: '10px',
  padding: '12px 14px',
  margin: '0 0 12px',
}
const title = { fontSize: '15px', fontWeight: 700, color: '#0b1220', margin: '0 0 6px', lineHeight: '1.35' }
const linkStyle = { color: '#0b1220', textDecoration: 'none' }
const meta = { fontSize: '11px', color: '#7b8394', margin: '0' }
const cta = { fontSize: '13px', color: '#1d4ed8', margin: '14px 0 0' }
const foot = { fontSize: '11px', color: '#8a92a1', margin: '18px 0 0' }
const disclaimer = { fontSize: '11px', color: '#9ca3af', fontStyle: 'italic' as const, margin: '12px 0 0' }

const GeminiFlyer = ({ dateLabel = '', imageUrl = '', items = [] }: Props) => (
  <Html lang="en" dir="ltr">
    <Head />
    <Preview>{`Global Bioenergy Watch daily flyer — ${dateLabel}`}</Preview>
    <Body style={main}>
      <Container style={container}>
        <Section style={banner}>
          <Text style={bannerTitle}>Global Bioenergy Watch</Text>
          <Text style={bannerSub}>AI-generated daily flyer · {dateLabel}</Text>
        </Section>

        <Section style={inner}>
          <Text style={kicker}>Top global bioenergy policy headlines</Text>

          {items.length === 0 ? (
            <Text style={meta}>No headlines available for today.</Text>
          ) : (
            items.map((it, i) => (
              <Section key={it.url ?? i} style={card}>
                <Text style={title}>
                  <Link href={it.url} style={linkStyle}>
                    {it.title}
                  </Link>
                </Text>
                <Text style={meta}>
                  {[it.source, it.countryName, (it.fuels ?? []).join(', ')].filter(Boolean).join(' · ')}
                </Text>
              </Section>
            ))
          )}
        </Section>

        {imageUrl ? (
          <Section style={imageWrap}>
            <Link href={imageUrl}>
              <img src={imageUrl} alt="Global Bioenergy Watch daily flyer" style={image} />
            </Link>
          </Section>
        ) : null}

        <Section style={inner}>
          <Hr />
          <Text style={cta}>
            <Link href="https://globalbioenergywatch.org/timeline" style={{ color: '#1d4ed8' }}>
              See the full policy timeline →
            </Link>
          </Text>
          <Text style={disclaimer}>
            This flyer image was generated by AI and may contain errors. Always cross-verify with the source links before sharing.
          </Text>
          <Text style={foot}>Sent automatically from globalbioenergywatch.org</Text>
        </Section>
      </Container>
    </Body>
  </Html>
)

export const template = {
  component: GeminiFlyer,
  subject: (data: Record<string, any>) =>
    `Global Bioenergy Watch — Daily flyer · ${data['dateLabel'] || new Date().toLocaleDateString('en-GB', { day: 'numeric', month: 'long', year: 'numeric', timeZone: 'UTC' })}`,
  displayName: 'AI-generated daily flyer',
  previewData: {
    dateLabel: 'Wednesday, 12 August 2026',
    imageUrl: 'https://globalbioenergywatch.org/api/public/flyer-image?day=2026-08-27',
    items: [
      {
        title: 'EPA finalises 2027 Renewable Fuel Standard volumes',
        url: 'https://example.com/rfs',
        source: 'epa.gov',
        countryName: 'United States',
        fuels: ['Ethanol'],
      },
    ],
  },
} satisfies TemplateEntry
