import React from "react";
import {
  Body,
  Container,
  Head,
  Heading,
  Hr,
  Html,
  Link,
  Preview,
  Text,
} from "@react-email/components";
import type { TemplateEntry } from "../registry";

interface Props {
  panel?: string;
  measureLabel?: string;
  filterLabel?: string;
  summary?: string;
  dateLabel?: string;
  sources?: string[];
  referenceNote?: string;
}

const main = {
  backgroundColor: "#ffffff",
  fontFamily: "Calibri, Carlito, Segoe UI, Arial, sans-serif",
};
const container = { padding: "24px 28px", maxWidth: "640px" };
const kicker = {
  fontSize: "11px",
  color: "#1257d6",
  textTransform: "uppercase" as const,
  letterSpacing: "0.09em",
  fontWeight: 700,
  margin: "0 0 6px",
};
const heading = { fontSize: "23px", lineHeight: "1.25", margin: "0 0 8px", color: "#0b1220" };
const meta = {
  fontSize: "11px",
  color: "#6b7484",
  textTransform: "uppercase" as const,
  letterSpacing: "0.05em",
  margin: "0 0 16px",
};
const sectionLabel = {
  fontSize: "11px",
  color: "#0b1220",
  textTransform: "uppercase" as const,
  letterSpacing: "0.09em",
  fontWeight: 700,
  margin: "0 0 6px",
};
const text = { fontSize: "14px", color: "#2c3444", margin: "0 0 14px", lineHeight: "1.6" };
const link = { color: "#1257d6", fontSize: "13px", fontWeight: 700 };
const foot = { fontSize: "11px", color: "#8a92a1", margin: "18px 0 0", lineHeight: "1.5" };

const ChartSummary = ({
  panel = "",
  measureLabel = "",
  filterLabel = "All entities",
  summary = "",
  dateLabel = "",
  sources = [],
  referenceNote = "",
}: Props) => (
  <Html lang="en" dir="ltr">
    <Head />
    <Preview>{`AI summary: ${panel}`}</Preview>
    <Body style={main}>
      <Container style={container}>
        <Text style={kicker}>Global Bioenergy Watch — Chart summary</Text>
        <Heading style={heading}>{panel}</Heading>
        <Text style={meta}>
          {[measureLabel, filterLabel, dateLabel].filter(Boolean).join(" — ")}
        </Text>

        <Hr />
        <Text style={sectionLabel}>AI summary</Text>
        {summary
          .split(/\n{2,}/)
          .filter(Boolean)
          .map((para, i) => (
            <Text key={i} style={text}>
              {para}
            </Text>
          ))}

        <Hr />
        <Text style={sectionLabel}>Data sources &amp; references</Text>
        {sources.map((s, i) => (
          <Text key={i} style={{ ...text, margin: "0 0 8px" }}>
            • {s}
          </Text>
        ))}
        {referenceNote ? <Text style={foot}>{referenceNote}</Text> : null}

        <Hr />
        <Link style={link} href="https://www.globalbioenergywatch.org">
          Open Global Bioenergy Watch
        </Link>
        <Text style={foot}>
          This summary was generated by AI from the chart view you selected. It may contain errors —
          always cross-verify against primary sources before acting on it.
        </Text>
      </Container>
    </Body>
  </Html>
);

export const template = {
  component: ChartSummary,
  subject: (data: Record<string, any>) =>
    `Global Bioenergy Market and Policy Updates — ${data["dateLabel"] || new Date().toUTCString().slice(0, 16)}`,
  displayName: "Chart summary",
  previewData: {
    panel: "Top global oil companies",
    measureLabel: "Annual capacity (MMboe/yr)",
    filterLabel: "All countries · Top 10",
    dateLabel: "Thu, 20 Aug 2026",
    summary:
      "Saudi Aramco dominates the ranking on annual output capacity, with several times the volume of the next largest producer.",
    sources: [
      "Annual output capacity (MMboe/yr): company annual reports and 20-F/10-K filings.",
      "Market capitalisation: approximate values from company disclosures.",
    ],
    referenceNote:
      "Figures are estimates compiled by Global Bioenergy Watch and may lag official filings — always cross-verify against the primary sources listed.",
  },
} satisfies TemplateEntry;
