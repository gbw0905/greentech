/** Formatted market cap for a ticker, e.g. "$480 bn" / "$1.2 tn", or null. */
export function marketCapLabel(ticker: string | null | undefined): string | null {
  if (!ticker) return null;
  const bn = MARKET_CAP_USD_BN[ticker];
  if (!bn) return null;
  return bn >= 1000 ? `$${(bn / 1000).toFixed(1)} tn` : `$${bn} bn`;
}

/** Numeric market cap (USD billions) for ranking, 0 when unlisted/unknown. */
export function marketCapValue(ticker: string | null | undefined): number {
  if (!ticker) return 0;
  return MARKET_CAP_USD_BN[ticker] ?? 0;
}

