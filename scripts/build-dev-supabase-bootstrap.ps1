param(
  [string]$OutputPath = "supabase/dev-bootstrap.sql"
)

$ErrorActionPreference = "Stop"

$repositoryRoot = Split-Path -Parent $PSScriptRoot
$migrationDirectory = Join-Path $repositoryRoot "supabase/migrations"
$resolvedOutput = Join-Path $repositoryRoot $OutputPath

# These migrations contain only production HTTP cron jobs.
$excludedMigrations = @(
  "20260808160630_b14ad617-3498-419d-81da-3c46d4635316.sql",
  "20260812153623_4626e4ef-d93b-4f83-84ca-2d5f9bb068f0.sql",
  "20260817225239_c815842b-8de8-4f51-aeec-30f7412fa7cd.sql",
  "20260827152939_6d4b40bb-66c8-42a1-96a8-90f67745544f.sql"
)

# These migrations mix schema/data changes with production cron configuration.
# Keep only the safe prefix of each file.
$safePrefixLineCounts = @{
  "20260806174036_e0250e59-8ff1-4b54-8c52-ae7b90a7d3f7.sql" = 36
  "20260819154552_4947a64a-672f-4b66-b58e-730f7d656cf7.sql" = 9
}

$header = @"
-- DEVELOPMENT ONLY: schema bootstrap generated from supabase/migrations.
-- Production HTTP cron jobs, production URLs, and embedded deployment keys are omitted.
-- This creates database structure and migration data; it does not copy production rows
-- from application, auth, or storage tables.
-- Generated by scripts/build-dev-supabase-bootstrap.ps1.

"@

$sections = [System.Collections.Generic.List[string]]::new()
$sections.Add($header)

Get-ChildItem -LiteralPath $migrationDirectory -Filter "*.sql" |
  Sort-Object Name |
  ForEach-Object {
    if ($excludedMigrations -contains $_.Name) {
      return
    }

    $lines = @(Get-Content -LiteralPath $_.FullName)
    if ($safePrefixLineCounts.ContainsKey($_.Name)) {
      $lineCount = $safePrefixLineCounts[$_.Name]
      $lines = @($lines | Select-Object -First $lineCount)
    }

    $sections.Add("-- BEGIN MIGRATION: $($_.Name)")
    $sections.Add(($lines -join [Environment]::NewLine))
    $sections.Add("-- END MIGRATION: $($_.Name)`n")
  }

$sections.Add(@"
-- DEVELOPMENT SAFETY: do not retain the production LinkedIn organization target.
UPDATE public.linkedin_settings
SET company_page_url = '', company_org_id = '', posting_mode = 'personal_mention'
WHERE id = true;

ALTER TABLE public.linkedin_settings
  ALTER COLUMN company_page_url SET DEFAULT '',
  ALTER COLUMN company_org_id SET DEFAULT '';
"@)

$outputDirectory = Split-Path -Parent $resolvedOutput
New-Item -ItemType Directory -Path $outputDirectory -Force | Out-Null
[System.IO.File]::WriteAllText(
  $resolvedOutput,
  ($sections -join [Environment]::NewLine),
  [System.Text.UTF8Encoding]::new($false)
)

Write-Output $resolvedOutput
